function plotGraphvizStatic(adj, labels, varargin)
warning('PMTK:StaticGraphRenderer', ...
    'Using a static Graphviz preview; interactive MATLAB graph-object editing is unavailable in this renderer.');
graphviz(adj, 'labels', labels, varargin{:}, 'preview', true);
annotation(gcf, 'textbox', [0 0 1 0.045], ...
    'String', 'Static Graphviz rendering; MATLAB graph-object editing unavailable', ...
    'HorizontalAlignment', 'center', 'LineStyle', 'none', 'FontSize', 8);
end
